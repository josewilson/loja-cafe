-- Fase 3b: fechamento de caixa por turno. Cada pedido vendido (PAGO e não cancelado) entra em UM fechamento.

CREATE TABLE fechamento_caixa (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loja_id           bigint NOT NULL REFERENCES loja (id),
    usuario_id        bigint REFERENCES usuario (id),          -- nulo só no fechamento "histórico" da migração
    desde             timestamp(6) with time zone,              -- fim do fechamento anterior (nulo no primeiro de uma loja nova)
    ate               timestamp(6) with time zone NOT NULL,
    pedidos           integer NOT NULL,
    total             numeric(12,2) NOT NULL,
    dinheiro_esperado numeric(12,2) NOT NULL,                   -- o que DINHEIRO vendeu no turno
    dinheiro_contado  numeric(12,2) NOT NULL CHECK (dinheiro_contado >= 0),
    diferenca         numeric(12,2) NOT NULL,                   -- contado - esperado (negativa = faltou)
    observacao        varchar(140),
    criado_em         timestamp(6) with time zone NOT NULL
);
CREATE INDEX idx_fechamento_loja ON fechamento_caixa (loja_id, id DESC);

ALTER TABLE pedido ADD COLUMN fechamento_id bigint REFERENCES fechamento_caixa (id);

-- Tudo que já foi vendido antes do caixa existir vira um fechamento "histórico" por loja,
-- para o primeiro turno de verdade começar do zero.
INSERT INTO fechamento_caixa (loja_id, usuario_id, desde, ate, pedidos, total, dinheiro_esperado, dinheiro_contado, diferenca, observacao, criado_em)
SELECT l.id, NULL,
       MIN(p.criado_em) FILTER (WHERE p.status = 'PAGO' AND p.preparo <> 'CANCELADO'),
       now(),
       COUNT(p.id) FILTER (WHERE p.status = 'PAGO' AND p.preparo <> 'CANCELADO'),
       COALESCE(SUM(p.valor) FILTER (WHERE p.status = 'PAGO' AND p.preparo <> 'CANCELADO'), 0),
       COALESCE(SUM(p.valor) FILTER (WHERE p.status = 'PAGO' AND p.preparo <> 'CANCELADO' AND p.forma_pagamento = 'DINHEIRO'), 0),
       COALESCE(SUM(p.valor) FILTER (WHERE p.status = 'PAGO' AND p.preparo <> 'CANCELADO' AND p.forma_pagamento = 'DINHEIRO'), 0),
       0,
       'Histórico anterior ao fechamento de caixa',
       now()
FROM loja l LEFT JOIN pedido p ON p.loja_id = l.id
GROUP BY l.id;

UPDATE pedido SET fechamento_id = f.id
FROM fechamento_caixa f
WHERE f.loja_id = pedido.loja_id AND pedido.status = 'PAGO' AND pedido.preparo <> 'CANCELADO';

-- O turno aberto de cada loja: pedidos pagos ainda sem fechamento.
CREATE INDEX idx_pedido_turno_aberto ON pedido (loja_id) WHERE fechamento_id IS NULL AND status = 'PAGO';
-- Relatório do dia: pedidos de uma loja por data de criação.
CREATE INDEX idx_pedido_loja_criado ON pedido (loja_id, criado_em);
