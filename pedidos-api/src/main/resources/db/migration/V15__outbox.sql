-- Outbox: o evento nasce na mesma transação do pedido e um relé o entrega ao Kafka depois (at-least-once).
-- Assim o banco e o broker não divergem: sem commit não há evento, e com commit o evento sai, mesmo que o Kafka esteja fora na hora.
CREATE TABLE evento_saida (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topico     varchar(60) NOT NULL,
    chave      varchar(60) NOT NULL,
    payload    varchar(4000) NOT NULL,
    criado_em  timestamp(6) with time zone NOT NULL,
    enviado_em timestamp(6) with time zone
);
CREATE INDEX idx_evento_saida_pendente ON evento_saida (id) WHERE enviado_em IS NULL;
