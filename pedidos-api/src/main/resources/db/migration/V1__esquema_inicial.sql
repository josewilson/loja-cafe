-- Esquema inicial (o que a API já usava quando o Flyway entrou). Banco novo roda este arquivo;
-- banco que já existia é marcado como "versão 1" e começa a partir da V2 (baseline-on-migrate).

CREATE TABLE produto (
    id        bigint PRIMARY KEY,
    nome      varchar(255),
    descricao varchar(255),
    emoji     varchar(255),
    preco     numeric(10,2),
    estoque   integer
);

CREATE TABLE usuario (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       varchar(255),
    email      varchar(255) UNIQUE,
    senha_hash varchar(255)
);

CREATE TABLE sessao (
    token_hash varchar(255) PRIMARY KEY,
    usuario_id bigint NOT NULL REFERENCES usuario (id),
    expira_em  timestamp(6) with time zone
);

CREATE TABLE pedido (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      bigint REFERENCES usuario (id),
    cliente         varchar(255),
    forma_pagamento varchar(255) CHECK (forma_pagamento IN ('PIX', 'CREDITO', 'DEBITO', 'DINHEIRO')),
    parcelas        integer,
    observacao      varchar(255),
    valor           numeric(10,2),
    status          varchar(255) CHECK (status IN ('AGUARDANDO_PAGAMENTO', 'PAGO', 'RECUSADO')),
    motivo          varchar(255),
    processado_por  varchar(255),
    criado_em       timestamp(6) with time zone
);

CREATE TABLE item_pedido (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id      bigint REFERENCES pedido (id),
    produto_id     bigint,
    item           varchar(255),
    quantidade     integer NOT NULL,
    tamanho        varchar(255) CHECK (tamanho IN ('PEQUENO', 'MEDIO', 'GRANDE')),
    preco_unitario numeric(10,2),
    valor          numeric(10,2)
);

CREATE TABLE item_pedido_extras (
    item_pedido_id bigint NOT NULL REFERENCES item_pedido (id),
    extras         varchar(255) CHECK (extras IN ('LEITE_VEGETAL', 'CHANTILLY', 'CARAMELO', 'CANELA'))
);
