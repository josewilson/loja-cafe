-- Fase 3c-2: insumos (matéria-prima), ficha técnica de produtos e extras, estoque de insumos por loja e consumo por pedido.

CREATE TABLE insumo (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome    varchar(60) NOT NULL,
    unidade varchar(2) NOT NULL CHECK (unidade IN ('G', 'ML', 'UN')),   -- imutável depois de criado
    ativo   boolean NOT NULL DEFAULT true
);
CREATE UNIQUE INDEX uk_insumo_nome ON insumo (lower(nome));

-- Estoque de insumo por loja. A quantidade PODE ficar negativa: a venda nunca é bloqueada, só gera alerta.
CREATE TABLE estoque_insumo (
    loja_id    bigint NOT NULL REFERENCES loja (id),
    insumo_id  bigint NOT NULL REFERENCES insumo (id),
    quantidade numeric(14,3) NOT NULL DEFAULT 0,
    minimo     numeric(14,3) NOT NULL DEFAULT 0 CHECK (minimo >= 0),
    PRIMARY KEY (loja_id, insumo_id)
);

-- Ficha técnica: quanto de cada insumo gasta 1 unidade do produto (ou do extra), para o tamanho MÉDIO.
CREATE TABLE ficha_produto (
    produto_id bigint NOT NULL REFERENCES produto (id),
    insumo_id  bigint NOT NULL REFERENCES insumo (id),
    quantidade numeric(12,3) NOT NULL CHECK (quantidade > 0),
    PRIMARY KEY (produto_id, insumo_id)
);
CREATE TABLE ficha_extra (
    extra      varchar(20) NOT NULL CHECK (extra IN ('LEITE_VEGETAL', 'CHANTILLY', 'CARAMELO', 'CANELA')),
    insumo_id  bigint NOT NULL REFERENCES insumo (id),
    quantidade numeric(12,3) NOT NULL CHECK (quantidade > 0),
    PRIMARY KEY (extra, insumo_id)
);

-- O que cada pedido consumiu (uma "foto": a ficha pode mudar depois). Serve para devolver na recusa ou no cancelamento.
CREATE TABLE consumo_pedido (
    pedido_id  bigint NOT NULL REFERENCES pedido (id),
    insumo_id  bigint NOT NULL REFERENCES insumo (id),
    quantidade numeric(14,3) NOT NULL,
    PRIMARY KEY (pedido_id, insumo_id)
);
