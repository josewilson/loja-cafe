-- Fase 2: rede de lojas, papéis de usuário, estoque por loja e auditoria.
-- Tudo que já existia (contas, pedidos, estoque) passa a pertencer à loja "Matriz".

CREATE TABLE loja (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  varchar(120) NOT NULL UNIQUE,
    ativa boolean NOT NULL DEFAULT true
);
INSERT INTO loja (nome) VALUES ('Matriz');

-- Usuários: papel + loja. Só o ADMIN fica sem loja. As contas atuais viram ATENDENTE da Matriz.
ALTER TABLE usuario ADD COLUMN papel varchar(20);
ALTER TABLE usuario ADD COLUMN loja_id bigint REFERENCES loja (id);
ALTER TABLE usuario ADD COLUMN ativo boolean NOT NULL DEFAULT true;
UPDATE usuario SET papel = 'ATENDENTE', loja_id = (SELECT id FROM loja WHERE nome = 'Matriz');
ALTER TABLE usuario ALTER COLUMN papel SET NOT NULL;
ALTER TABLE usuario ADD CONSTRAINT usuario_papel_check CHECK (papel IN ('ADMIN', 'GERENTE', 'ATENDENTE', 'COZINHA'));
ALTER TABLE usuario ADD CONSTRAINT usuario_loja_check CHECK (papel = 'ADMIN' OR loja_id IS NOT NULL);
CREATE INDEX idx_usuario_loja_id ON usuario (loja_id);

-- Pedidos: loja onde foi vendido e quem lançou (atendente). "cliente" passa a ser o nome dito no balcão.
ALTER TABLE pedido ADD COLUMN loja_id bigint REFERENCES loja (id);
ALTER TABLE pedido ADD COLUMN atendente varchar(255);
UPDATE pedido SET loja_id = (SELECT id FROM loja WHERE nome = 'Matriz'), atendente = cliente;
ALTER TABLE pedido ALTER COLUMN loja_id SET NOT NULL;
CREATE INDEX idx_pedido_loja_id ON pedido (loja_id, id DESC);

-- Estoque por loja (o cardápio e o preço continuam da rede, na tabela produto).
CREATE TABLE estoque_loja (
    loja_id    bigint NOT NULL REFERENCES loja (id),
    produto_id bigint NOT NULL REFERENCES produto (id),
    quantidade integer NOT NULL CHECK (quantidade >= 0),
    PRIMARY KEY (loja_id, produto_id)
);
INSERT INTO estoque_loja (loja_id, produto_id, quantidade)
SELECT (SELECT id FROM loja WHERE nome = 'Matriz'), id, estoque FROM produto;
ALTER TABLE produto DROP COLUMN estoque;

-- Auditoria: quem fez o quê e quando.
CREATE TABLE auditoria (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quando      timestamp(6) with time zone NOT NULL,
    usuario_id  bigint,
    loja_id     bigint,
    acao        varchar(60) NOT NULL,
    entidade    varchar(60),
    entidade_id varchar(60),
    detalhe     varchar(500)
);
CREATE INDEX idx_auditoria_loja ON auditoria (loja_id, id DESC);
CREATE INDEX idx_auditoria_id ON auditoria (id DESC);
